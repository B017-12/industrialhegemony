/**
 * Resolves the part visual spec for any bound Valmet asset or unbound CV object.
 */
export function getPartVisualSpec(assetOrClass) {
  const rawClass = String(
    typeof assetOrClass === 'string'
      ? assetOrClass
      : assetOrClass?.asset_class || assetOrClass?.class || ''
  ).toLowerCase();
  const tag = String(assetOrClass?.tag || '').toUpperCase();

  if (tag.startsWith('CV-') || rawClass.includes('valve')) return PART_VISUAL_SPECS.control_valve;
  if (tag.startsWith('P-') || rawClass.includes('pump')) return PART_VISUAL_SPECS.process_pump;
  if (tag.startsWith('M-') || rawClass.includes('motor')) return PART_VISUAL_SPECS.electric_motor;
  if (tag.startsWith('PT-') || rawClass.includes('transmitter') || rawClass.includes('gauge'))
    return PART_VISUAL_SPECS.pressure_transmitter;
  if (tag.startsWith('VS-') || rawClass.includes('sensor'))
    return PART_VISUAL_SPECS.vibration_sensor;
  if (rawClass.includes('forklift') || rawClass.includes('truck') || rawClass.includes('chair'))
    return PART_VISUAL_SPECS.forklift;
  if (rawClass.includes('tote') || rawClass.includes('tank') || rawClass.includes('vessel') || rawClass.includes('box'))
    return PART_VISUAL_SPECS.ibc_tote;
  if (rawClass.includes('cabinet') || rawClass.includes('bench') || rawClass.includes('table'))
    return PART_VISUAL_SPECS.cabinet;

  return PART_VISUAL_SPECS.process_pump;
}

